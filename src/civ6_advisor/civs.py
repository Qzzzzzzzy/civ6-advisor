"""文明攻略库：每个文明的胜利倾向、宗教需求、扩张节奏、各阶段重点。

覆盖原版 + 迭起兴衰 + 风云变幻 + 新纪元季票的主要文明。没收录的文明（模组等）会退回到
"游戏里读到的能力描述 + 通用规则"，大模型分析时同样会拿到能力原文。

字段说明：
  focus      胜利/发展倾向，前面的优先
  religion   必需 / 可选 / 保底（必定拿到宗教，不用抢）/ 不能（无法创立宗教）
  expand     前期结束（标准速度约 100 回合）时建议的城市数
  traits     一句话特色
  phases     开局 / 前期 / 中期 / 后期 的重点
  flags      规则调整开关：low_science_ok（科研低是正常的）、gold_buy（主要靠买）、
             improve_bonus（改良资源有额外收益，改良科技更重要）、
             no_adjacent_center（区域不能挨市中心）、district_features（区域必须建在地貌上）
  leaders    同一文明不同领袖的差异
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class LeaderNote:
    name: str
    tip: str
    focus: tuple[str, ...] | None = None
    religion: str | None = None


@dataclass
class CivProfile:
    name: str
    focus: tuple[str, ...]
    traits: str
    phases: dict[str, str]
    religion: str = "可选"
    expand: int = 5
    flags: frozenset[str] = frozenset()
    leaders: dict[str, LeaderNote] = field(default_factory=dict)

    def for_leader(self, leader_type: str) -> "ResolvedProfile":
        ln = self.leaders.get(leader_type)
        return ResolvedProfile(
            civ=self,
            leader=ln,
            focus=(ln.focus if ln and ln.focus else self.focus),
            religion=(ln.religion if ln and ln.religion else self.religion),
        )


@dataclass
class ResolvedProfile:
    civ: CivProfile
    leader: LeaderNote | None
    focus: tuple[str, ...]
    religion: str

    @property
    def name(self) -> str:
        return self.civ.name

    @property
    def expand(self) -> int:
        return self.civ.expand

    def has(self, flag: str) -> bool:
        return flag in self.civ.flags

    def phase_tip(self, phase: str) -> str:
        return self.civ.phases.get(phase, "")

    @property
    def focus_text(self) -> str:
        return "/".join(self.focus)


def F(*xs: str) -> frozenset[str]:
    return frozenset(xs)


